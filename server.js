import http from 'node:http';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  scrapeNovelRinganSeries,
  scrapeNovelRinganChapter,
  scrapeMeioNovelSeries,
  scrapeMeioNovelChapter
} from './scraper.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORT = process.env.PORT || 4173;
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp'
};

let dbCache = null;

async function loadDb() {
  if (dbCache) return dbCache;
  try {
    const raw = await fs.readFile(path.join(__dirname, 'data', 'novels_db.json'), 'utf8');
    dbCache = JSON.parse(raw);
    return dbCache;
  } catch {
    dbCache = { scrapedAt: new Date().toISOString(), sources: [], totalNovels: 0, novels: [] };
    return dbCache;
  }
}

async function saveDb() {
  if (!dbCache) return;
  const dataDir = path.join(__dirname, 'data');
  await fs.mkdir(dataDir, { recursive: true });
  await fs.writeFile(path.join(dataDir, 'novels_db.json'), JSON.stringify(dbCache, null, 2), 'utf8');
  await fs.writeFile(
    path.join(dataDir, 'novels_db.js'),
    `// Auto-generated by KuroRead Web Scraper (NovelRingan & Meionovel)\nwindow.KUROREAD_DB = ${JSON.stringify(dbCache, null, 2)};\n`,
    'utf8'
  );
}

function sendJson(res, status, data) {
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type'
  });
  res.end(JSON.stringify(data));
}

async function searchLiveWeb(query) {
  const results = [];
  try {
    const rNr = await fetch(`https://novelringan.com/?s=${encodeURIComponent(query)}`, {
      headers: { 'User-Agent': UA }
    });
    if (rNr.ok) {
      const html = await rNr.text();
      const seen = new Set();
      const matches = [...html.matchAll(/href="(https:\/\/novelringan\.com\/series\/[^"]+)"[^>]*>([^<]+)<\/a>/gi)];
      for (const m of matches) {
        const url = m[1].trim();
        const title = m[2].replace(/Bahasa Indonesia/i, '').trim();
        if (!title || seen.has(url)) continue;
        seen.add(url);
        results.push({
          title,
          url,
          source: 'NovelRingan',
          type: 'novelringan'
        });
        if (results.length >= 8) break;
      }
    }
  } catch {}

  try {
    const rMeio = await fetch(`https://meionovels.com/?s=${encodeURIComponent(query)}&post_type=wp-manga`, {
      headers: { 'User-Agent': UA }
    });
    if (rMeio.ok) {
      const html = await rMeio.text();
      const seen = new Set();
      const matches = [...html.matchAll(/<div class="post-title">\s*<h3[^>]*>\s*<a href="(https:\/\/meionovels\.com\/novel\/[^"]+)">([\s\S]*?)<\/a>/gi)];
      for (const m of matches) {
        const url = m[1].trim();
        const title = m[2].replace(/<[^>]+>/g, '').trim();
        if (!title || seen.has(url)) continue;
        seen.add(url);
        results.push({
          title,
          url,
          source: 'Meionovel',
          type: 'meionovel'
        });
        if (results.length >= 12) break;
      }
    }
  } catch {}

  return results;
}

const server = http.createServer(async (req, res) => {
  if (req.method === 'OPTIONS') {
    sendJson(res, 200, { ok: true });
    return;
  }

  const parsedUrl = new URL(req.url, `http://localhost:${PORT}`);
  const pathname = parsedUrl.pathname;

  // 1. GET /api/novels
  if (pathname === '/api/novels' && req.method === 'GET') {
    const db = await loadDb();
    sendJson(res, 200, db);
    return;
  }

  // 2. GET /api/chapter?novelId=...&num=...&url=...
  if (pathname === '/api/chapter' && req.method === 'GET') {
    const novelId = parsedUrl.searchParams.get('novelId') || '';
    const num = Number(parsedUrl.searchParams.get('num') || '1');
    let targetUrl = parsedUrl.searchParams.get('url') || '';

    const db = await loadDb();
    const novel = db.novels.find(n => n.id === novelId);

    if (novel && novel.preloadedChapters && novel.preloadedChapters[num]) {
      sendJson(res, 200, { ok: true, cached: true, chapter: novel.preloadedChapters[num] });
      return;
    }

    if (!targetUrl && novel && Array.isArray(novel.chapterCatalog)) {
      const found = novel.chapterCatalog.find(c => Number(c.num) === num);
      if (found) targetUrl = found.url;
    }

    if (!targetUrl) {
      sendJson(res, 404, { ok: false, error: 'URL chapter tidak ditemukan' });
      return;
    }

    try {
      const isMeio = targetUrl.includes('meionovels.com');
      const scraped = isMeio
        ? await scrapeMeioNovelChapter(targetUrl)
        : await scrapeNovelRinganChapter(targetUrl);

      if (!scraped.paragraphs || scraped.paragraphs.length === 0) {
        sendJson(res, 422, { ok: false, error: 'Konten chapter kosong' });
        return;
      }

      const wordCount = scraped.paragraphs.join(' ').split(/\s+/).length;
      const readMins = Math.max(4, Math.round(wordCount / 180));
      const chapterObj = {
        num,
        code: String(num).padStart(3, '0'),
        title: scraped.title || `Chapter ${num}`,
        label: `Ch.${num}`,
        url: targetUrl,
        meta: `Live Scraped · ${readMins} menit`,
        readMins,
        paragraphs: scraped.paragraphs
      };

      if (novel) {
        novel.preloadedChapters = novel.preloadedChapters || {};
        novel.preloadedChapters[num] = chapterObj;
        await saveDb();
      }

      sendJson(res, 200, { ok: true, cached: false, chapter: chapterObj });
    } catch (err) {
      sendJson(res, 500, { ok: false, error: err.message });
    }
    return;
  }

  // 3. GET /api/search-web?q=...
  if (pathname === '/api/search-web' && req.method === 'GET') {
    const q = (parsedUrl.searchParams.get('q') || '').trim();
    if (!q) {
      sendJson(res, 200, { ok: true, results: [] });
      return;
    }
    const results = await searchLiveWeb(q);
    sendJson(res, 200, { ok: true, results });
    return;
  }

  // 4. POST /api/import-web
  if (pathname === '/api/import-web' && req.method === 'POST') {
    let body = '';
    for await (const chunk of req) body += chunk;
    try {
      const payload = JSON.parse(body || '{}');
      const seriesUrl = (payload.url || '').trim();
      if (!seriesUrl) {
        sendJson(res, 400, { ok: false, error: 'URL novel diperlukan' });
        return;
      }

      const db = await loadDb();
      const existing = db.novels.find(n => n.sourceUrl === seriesUrl);
      if (existing) {
        sendJson(res, 200, { ok: true, alreadyExists: true, novel: existing });
        return;
      }

      const isMeio = seriesUrl.includes('meionovels.com');
      const meta = isMeio
        ? await scrapeMeioNovelSeries(seriesUrl)
        : await scrapeNovelRinganSeries(seriesUrl);

      const id = 'web_' + Date.now().toString(36);
      let localCover = 'assets/tbate.png';
      if (meta.coverUrl) {
        try {
          const rCov = await fetch(meta.coverUrl, { headers: { 'User-Agent': UA } });
          if (rCov.ok) {
            const ext = meta.coverUrl.split('?')[0].endsWith('.png') ? 'png' : 'jpg';
            const relCov = `assets/covers/${id}.${ext}`;
            await fs.mkdir(path.join(__dirname, 'assets', 'covers'), { recursive: true });
            await fs.writeFile(path.join(__dirname, relCov), Buffer.from(await rCov.arrayBuffer()));
            localCover = relCov;
          }
        } catch {}
      }

      const preloadedChapters = {};
      for (const idx of [0, 1]) {
        const chEntry = meta.chapters[idx];
        if (!chEntry) continue;
        try {
          const chData = isMeio
            ? await scrapeMeioNovelChapter(chEntry.url)
            : await scrapeNovelRinganChapter(chEntry.url);
          if (chData.paragraphs && chData.paragraphs.length > 0) {
            const wordCount = chData.paragraphs.join(' ').split(/\s+/).length;
            const readMins = Math.max(4, Math.round(wordCount / 180));
            preloadedChapters[chEntry.num] = {
              num: chEntry.num,
              code: String(chEntry.num).padStart(3, '0'),
              title: chData.title || chEntry.label || `Chapter ${chEntry.num}`,
              label: chEntry.label,
              url: chEntry.url,
              meta: `Live Scraped · ${readMins} menit`,
              readMins,
              paragraphs: chData.paragraphs
            };
          }
        } catch {}
      }

      const newNovel = {
        id,
        title: meta.scrapedTitle || payload.title || 'Novel Baru',
        scrapedTitle: meta.scrapedTitle,
        altTitle: meta.source,
        author: meta.author || 'Anonim',
        rating: '4.7',
        rank: `#${db.novels.length + 1}`,
        status: meta.status || 'Ongoing',
        totalChapters: meta.totalChapters || meta.chapters.length,
        chaptersText: `${meta.totalChapters || meta.chapters.length} Chapter`,
        chaptersShort: `${meta.totalChapters || meta.chapters.length} CH`,
        cover: localCover,
        thumb: localCover,
        remoteCover: meta.coverUrl,
        source: meta.source,
        sourceUrl: meta.sourceUrl,
        weeklyFeatured: false,
        curatedTagline: (meta.synopsis || '').slice(0, 95) + '...',
        genres: meta.genres.length > 0 ? meta.genres.slice(0, 4) : ['Fantasy', 'Adventure'],
        synopsis: meta.synopsis || 'Novel terjemahan Bahasa Indonesia.',
        chapterCatalog: meta.chapters.map(c => ({
          num: c.num,
          code: String(c.num).padStart(3, '0'),
          label: c.label,
          url: c.url
        })),
        preloadedChapters
      };

      db.novels.unshift(newNovel);
      db.totalNovels = db.novels.length;
      await saveDb();

      sendJson(res, 200, { ok: true, novel: newNovel });
    } catch (err) {
      sendJson(res, 500, { ok: false, error: err.message });
    }
    return;
  }

  // Static files
  let relPath = pathname === '/' ? '/index.html' : decodeURIComponent(pathname);
  const safePath = path.normalize(path.join(__dirname, relPath));
  if (!safePath.startsWith(__dirname)) {
    res.writeHead(403);
    res.end('Forbidden');
    return;
  }

  if (fsSync.existsSync(safePath) && fsSync.statSync(safePath).isFile()) {
    const ext = path.extname(safePath).toLowerCase();
    res.writeHead(200, { 'Content-Type': MIME_TYPES[ext] || 'application/octet-stream' });
    fsSync.createReadStream(safePath).pipe(res);
  } else {
    res.writeHead(404);
    res.end('Not found');
  }
});

server.listen(PORT, () => {
  console.log(`KuroRead Live Scraper & App Server running at http://localhost:${PORT}`);
});
